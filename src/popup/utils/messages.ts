export function t(key: string, substitutions?: string | string[]): string {
  const values = Array.isArray(substitutions)
    ? substitutions
    : substitutions
      ? [substitutions]
      : []
  return values.reduce(
    (result, value, index) => result.replace(`$${index + 1}`, String(value)),
    MESSAGES[key] || key,
  )
}
